class Card:
    __slots__ = ("card_id", "note_id", "deck_id", "preset", "state", "step", "due_ts", "due_day", "ivl", "ease",
                 "stab", "last_ts", "deleted", "introduced")

    def __init__(self, card_id, note_id, deck_id, preset):
        self.card_id, self.note_id, self.deck_id, self.preset = card_id, note_id, deck_id, preset
        self.state, self.step, self.due_ts, self.due_day, self.ivl, self.ease = 0, 0, None, None, 0.0, 2.5
        self.stab, self.last_ts, self.deleted, self.introduced = 1.0, None, False, False


def simulate(user, cfg, rng, show_time=False):
    tz = cfg["tz"] * 3600
    local_day = lambda ts: int((ts + tz - 4 * 3600) // DAY)  # noqa: E731  (Anki day, 4 am rollover)
    presets, decks = cfg["presets"], cfg["decks"]
    note_decks = [d for d in decks if d[3] > 0]
    cards, notes, rows = [], {}, []
    first_day = local_day(cfg["start"])
    next_id = cfg["start"] * 1000

    def add_notes(day_start_ts, n):
        nonlocal next_id
        for _ in range(n):
            deck_id, _, preset_id, per_note = note_decks[rng.integers(len(note_decks))]
            next_id = max(next_id + int(rng.integers(2_000, 90_000)), day_start_ts * 1000)
            note_id = next_id
            notes[note_id] = []
            for k in range(per_note):
                c = Card(note_id + 3 + 2 * k, note_id, deck_id, preset_id)
                c.stab = float(rng.lognormal(0.0, 0.6))
                cards.append(c)
                notes[note_id].append(c)
            next_id += 3 + 2 * per_note

    def recall_p(c, now):
        if c.state in (0, 1, 3):
            return 0.78 if c.state == 0 else (0.85 if c.step == 0 else 0.92)
        days = max(now - c.last_ts, 0) / DAY
        return (1 + days / (9 * c.stab)) ** -1

    def answer(c, now, rating):
        p = presets[c.preset]
        fuzz = lambda iv: max(1, int(round(iv * rng.uniform(0.95, 1.05))))  # noqa: E731
        if c.state in (0, 1):
            steps = p["learn"]
            if rating == 4:
                c.state, c.ivl = 2, float(p["easy_iv"])
            elif rating == 1:
                c.state, c.step = 1, 0
            elif rating == 2:
                c.state = 1
            else:
                c.state, c.step = 1, c.step + 1
                if c.step >= len(steps):
                    c.state, c.ivl = 2, 1.0
            if c.state == 1:
                delay = steps[min(c.step, len(steps) - 1)] * (1.5 if rating == 2 else 1.0)
                c.due_ts = now + delay
            c.introduced = True
        elif c.state == 2:
            late = max(0.0, (now - c.last_ts) / DAY - c.ivl) if c.last_ts else 0.0
            if rating == 1:
                c.ease, c.ivl, c.state, c.step = max(1.3, c.ease - 0.2), max(1.0, c.ivl * 0.2), 3, 0
                c.due_ts = now + p["relearn"][0]
            elif rating == 2:
                c.ease, c.ivl = max(1.3, c.ease - 0.15), max(c.ivl + 1, c.ivl * 1.2)
            elif rating == 3:
                c.ivl = max(c.ivl + 1, (c.ivl + late / 2) * c.ease)
            else:
                c.ease, c.ivl = c.ease + 0.15, max(c.ivl + 1, (c.ivl + late) * c.ease * 1.3)
        else:  # relearning
            steps = p["relearn"]
            if rating == 1:
                c.step = 0
            elif rating in (2, 3):
                c.step += 0 if rating == 2 else 1
            if rating == 4 or c.step >= len(steps):
                c.state = 2
            else:
                c.due_ts = now + steps[c.step] * (1.5 if rating == 2 else 1.0)
        if c.state == 2:
            c.due_day = local_day(now) + fuzz(min(c.ivl, 365.0))
            c.due_ts = None
        # hidden memory strength
        days = max(now - c.last_ts, 0) / DAY if c.last_ts else 0.0
        if rating == 1:
            c.stab = max(0.3, c.stab * 0.35)
        else:
            c.stab = c.stab * (1 + (1.2 + 0.3 * (rating - 2)) * math.exp(-0.15 * math.log1p(c.stab)) *
                               (0.3 + min(days / max(c.stab, 0.1), 3.0)))
        c.last_ts = now

    deletions = {first_day + d: what for d, what in cfg["delete"]}
    for d in range(cfg["days"]):
        day = first_day + d
        day_start = (day * DAY) - tz + 4 * 3600
        if d == 0 or rng.random() < cfg["add_p"]:
            add_notes(day_start + int(rng.integers(5 * 3600, 9 * 3600)), int(rng.integers(*cfg["add_n"])))
        if day in deletions:  # delete reviewed cards (they stay in the revlogs, vanish from the cards table)
            seen = [c for c in cards if c.introduced and not c.deleted]
            if deletions[day] == "note":
                pool = [n for n, cs in notes.items() if len(cs) > 1 and all(c.introduced and not c.deleted for c in cs)]
                victims = notes[pool[int(rng.integers(len(pool)))]]
            else:
                pool = [c for c in seen if len(notes[c.note_id]) > 1]
                victims = [pool[int(rng.integers(len(pool)))]]
            for c in victims:
                c.deleted = True
        if rng.random() > cfg["study_p"] and d > 0:
            continue
        sessions = 1 + int(rng.random() < cfg["second_session_p"])
        new_left = {pid: p["new"] for pid, p in presets.items()}
        for s in range(sessions):
            h = rng.normal(*cfg["hour"]) + (s * rng.uniform(3, 6) * (1 if cfg["hour"][0] < 14 else -1))
            now = float(day_start - 4 * 3600 + min(max(h, 4.5), 27.5) * 3600)
            active = [c for c in cards if not c.deleted]
            reviews = [c for c in active if c.state == 2 and c.due_day is not None and c.due_day <= day]
            rng.shuffle(reviews)
            reviews = reviews[:220]
            new = []
            if s == 0:
                for c in active:
                    if not c.introduced and new_left[c.preset] > 0:
                        new.append(c)
                        new_left[c.preset] -= 1
            queue = reviews + new
            order = rng.permutation(len(queue))
            queue = [queue[i] for i in order]
            while True:
                learning = [c for c in active if c.state in (1, 3) and c.due_ts is not None]
                due_now = [c for c in learning if c.due_ts <= now]
                if due_now:
                    c = min(due_now, key=lambda x: x.due_ts)
                elif queue:
                    c = queue.pop()
                    if c.deleted:
                        continue
                else:
                    soon = [c for c in learning if c.due_ts <= now + 25 * 60]
                    if not soon:
                        break
                    c = min(soon, key=lambda x: x.due_ts)
                    now = c.due_ts + rng.uniform(1, 20)
                state = c.state
                if rng.random() < recall_p(c, now):
                    g = cfg["grades"]
                    rating = int(rng.choice([2, 3, 4], p=np.array(g) / sum(g)))
                else:
                    rating = 1
                true_ms = int(rng.lognormal(math.log(cfg["dur_median"] * 1000 * (1.4 if rating == 1 else 1.0)), 0.7))
                if rng.random() < cfg["afk_p"]:
                    true_ms = int(rng.uniform(55_000, 600_000))
                true_ms = max(true_ms, 400)
                cap = presets[c.preset]["cap"] * 1000
                taken = min(true_ms, cap)
                answer_ts = now + true_ms / 1000
                revlog_id = int(round(answer_ts * 1000))
                review_time = revlog_id - taken          # dataset: review_time = revlog.id - taken_millis
                rows.append((c.card_id, revlog_id, review_time, rating, state, taken))
                answer(c, answer_ts, rating)
                now = answer_ts + rng.uniform(0.5, 4.0)
    # notes added after the last session: in the cards table, never reviewed
    add_notes((first_day + cfg["days"]) * DAY - tz + 4 * 3600 - 3600, cfg["final_batch"])
    rev = pd.DataFrame(rows, columns=["card_id", "revlog_id", "review_time", "rating", "state", "duration"])
    # original layout (the one training and scoring read): times from the revlog id (answer time); show-time layout:
    # from review_time = revlog id - taken_millis, plus the review_time column
    clock = "review_time" if show_time else "revlog_id"
    rev = rev.sort_values(clock, kind="stable").reset_index(drop=True)
    rev_day = ((rev[clock] // 1000 + tz - 4 * 3600) // DAY).astype(np.int64)
    rev["day_offset"] = rev_day - rev_day.min()
    prev_t = rev.groupby("card_id")[clock].shift(1)
    prev_d = rev.groupby("card_id")["day_offset"].shift(1)
    first = prev_t.isna()
    rev["elapsed_seconds"] = np.where(first, -1, np.maximum((rev[clock] - prev_t) // 1000, 0)).astype(np.int64)
    rev["elapsed_days"] = np.where(first, -1, np.maximum(rev["day_offset"] - prev_d, 0)).astype(np.int64)
    assert (rev.loc[first, "state"] == 0).all() and (rev.loc[~first, "state"] != 0).all()
    rev = rev[["card_id", "day_offset", "rating", "state", "duration", "elapsed_days", "elapsed_seconds"]
              + (["review_time"] if show_time else [])].astype(np.int64)
    # the dataset keeps its builder's row index (grouped by card); mimic that so the stored pandas index is not a range
    rev.index = pd.Index(np.argsort(np.lexsort((np.arange(len(rev)), rev["card_id"]))), dtype=np.int64)
    kept = [c for c in cards if not c.deleted]
    card_df = pd.DataFrame({"card_id": [c.card_id for c in kept], "note_id": [c.note_id for c in kept],
                            "deck_id": [c.deck_id for c in kept]}, dtype=np.int64)
    deck_df = pd.DataFrame([(d, p, pr) for d, p, pr, _ in decks], columns=["deck_id", "parent_id", "preset_id"],
                           dtype=np.int64)
    deleted = {c.card_id for c in cards if c.deleted}
    return rev, card_df, deck_df, deleted


def write(df, path, note):
    path.parent.mkdir(parents=True, exist_ok=True)
    table = pa.Table.from_pandas(df, preserve_index=not isinstance(df.index, pd.RangeIndex))
    table = table.replace_schema_metadata({**(table.schema.metadata or {}), b"synthetic": note.encode()})
    pq.write_table(table, path)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out", type=Path, help="scratch dataset folder (gets revlogs/, cards/, decks/)")
    ap.add_argument("--users", type=int, nargs="+", default=sorted(USERS))
    ap.add_argument("--show-time-layout", action="store_true",
                    help="write the newer dataset layout (review_time column, show-time intervals) instead of the "
                         "original layout that training and the test vectors use")
    args = ap.parse_args()
    out = args.out.resolve()
    repo_data = (Path(__file__).resolve().parent.parent / "data").resolve()
    if out == repo_data or repo_data in out.parents:
        sys.exit(f"refusing to write synthetic users into the dataset folder {repo_data}")
    note = NOTE.format(seed=SEED)
    summary = {}
    for user in args.users:
        rng = np.random.default_rng([SEED, user])
        rev, card_df, deck_df, deleted = simulate(user, USERS[user], rng, args.show_time_layout)
        for name, df in (("revlogs", rev), ("cards", card_df), ("decks", deck_df)):
            write(df, out / name / f"user_id={user}" / "data.parquet", note)
        del_rows = rev["card_id"].isin(deleted)
        summary[user] = {
            "reviews": len(rev), "days": int(rev["day_offset"].max()) + 1, "cards_reviewed": int(rev["card_id"].nunique()),
            "cards_table": len(card_df), "notes": int(card_df["note_id"].nunique()),
            "multi_card_notes": int((card_df.groupby("note_id").size() > 1).sum()), "decks": len(deck_df),
            "presets": int(deck_df["preset_id"].nunique()), "deleted_cards": len(deleted),
            "deleted_card_reviews": int(del_rows.sum()),
            "states": {int(k): int(v) for k, v in rev["state"].value_counts().sort_index().items()},
            "ratings": {int(k): int(v) for k, v in rev["rating"].value_counts().sort_index().items()},
            "same_day_repeats": int((rev["elapsed_days"] == 0).sum()),
            "duration_capped_60s": int((rev["duration"] == 60_000).sum()),
            "duration_over_60s": int((rev["duration"] > 60_000).sum()),
            "duration_median_ms": int(rev["duration"].median()),
        }
    (out / "SYNTHETIC_README.txt").write_text(
        note + ".\nUsers: " + ", ".join(map(str, args.users)) + "\n" + json.dumps(summary, indent=1) + "\n",
        encoding="utf-8")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
